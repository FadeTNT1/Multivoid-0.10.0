# gen_exports.ps1 -- regenerates the three export-surface files of the dwmapi proxy from the output of
#   dumpbin /exports C:\Windows\System32\dwmapi.dll
# The proxy forwards the FULL export set of the real dwmapi.dll (named and ordinal-only) through lazy
# trampolines (see dwmapi_stubs.asm). Run only when Windows grows a dwmapi export we must carry:
#   powershell -File gen_exports.ps1 -ExportsTxt dwm_exports.txt
# Outputs (checked in, never hand-edited): dwmapi_proxy.def, dwmapi_stubs.asm, dwmapi_exports.inc.
param([Parameter(Mandatory)][string]$ExportsTxt)
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$rows = @{}   # ordinal -> name or $null
foreach ($line in Get-Content -LiteralPath $ExportsTxt) {
    if ($line -match '^\s+(\d+)\s+[0-9A-F]+\s+[0-9A-F]{8}\s+(\w+)\s*$')        { $rows[[int]$Matches[1]] = $Matches[2] }
    elseif ($line -match '^\s+(\d+)\s+[0-9A-F]{8}\s+\[NONAME\]\s*$')            { $rows[[int]$Matches[1]] = $null }
}
if ($rows.Count -lt 100) { throw "parsed only $($rows.Count) exports from $ExportsTxt" }
$ords = $rows.Keys | Sort-Object
$base = $ords[0]
for ($i = 0; $i -lt $ords.Count; $i++) {
    if ($ords[$i] -ne $base + $i) { throw "ordinals are not contiguous at $($ords[$i]) -- slot = ordinal - base would break" }
}

$hdr = 'GENERATED by gen_exports.ps1 from `dumpbin /exports dwmapi.dll` -- do not edit by hand.'
$def = New-Object System.Collections.Generic.List[string]
$asm = New-Object System.Collections.Generic.List[string]
$inc = New-Object System.Collections.Generic.List[string]
$def.Add("; $hdr"); $def.Add('LIBRARY dwmapi'); $def.Add('EXPORTS')
$inc.Add("// $hdr"); $inc.Add("// One row per slot, slot i = ordinal (kOrdinalBase + i): the export's name, or null for an ordinal-only export.")
$inc.Add("constexpr unsigned kOrdinalBase = $base;"); $inc.Add("constexpr unsigned kSlotCount = $($ords.Count);")
$inc.Add('constexpr const char* kExportNames[kSlotCount] = {')

$asm.Add("; $hdr")
$asm.Add('; The 112 export stubs: each loads its slot number in EAX (not an argument register in the Windows x64 ABI)')
$asm.Add('; and tail-jumps through mv_targets[slot]. A slot starts out pointing at mv_resolve, which resolves the')
$asm.Add('; real function, patches the slot and jumps to it; afterwards the stub is one mov and one indirect jmp.')
$asm.Add('')
$asm.Add('PUBLIC mv_targets')
$asm.Add('EXTERN mv_resolve_slot:PROC')
$asm.Add('')
$asm.Add('.data')
$asm.Add("mv_targets QWORD $($ords.Count) dup (mv_resolve)")
$asm.Add('')
$asm.Add('.code')
foreach ($o in $ords) {
    $slot = $o - $base
    $n = $rows[$o]
    $asm.Add("PUBLIC mv_fwd_$slot")
    $asm.Add("mv_fwd_$slot PROC")
    $asm.Add("    mov eax, $slot")
    $asm.Add("    jmp qword ptr [mv_targets + $($slot * 8)]")
    $asm.Add("mv_fwd_$slot ENDP")

    if ($n) { $def.Add("    $n = mv_fwd_$slot @$o") } else { $def.Add("    mv_fwd_$slot @$o NONAME") }
    $inc.Add($(if ($n) { "    `"$n`"," } else { '    nullptr,' }) + "  // $o")
}
$inc.Add('};')
# The shared resolver lives with the generated table so mv_targets' initialiser can name it.
$asm.Add('')
$asm.Add(@'
; Entered by a tail jmp from a stub, EAX = slot, the caller's arguments still in RCX/RDX/R8/R9/XMM0-3 and on the
; stack. Save the register arguments, ask the C resolver for the real address (it also patches mv_targets), restore,
; and tail-jump: the real function sees exactly the call the game made.
mv_resolve PROC
    push rcx
    push rdx
    push r8
    push r9                       ; 4 pushes + return address = 40 bytes: rsp = 8 (mod 16)
    sub  rsp, 104                 ; 32 shadow + 4*16 xmm + 8 pad: rsp = 0 (mod 16) at the call
    movdqu xmmword ptr [rsp+32], xmm0
    movdqu xmmword ptr [rsp+48], xmm1
    movdqu xmmword ptr [rsp+64], xmm2
    movdqu xmmword ptr [rsp+80], xmm3
    mov  ecx, eax
    call mv_resolve_slot
    mov  r11, rax
    movdqu xmm0, xmmword ptr [rsp+32]
    movdqu xmm1, xmmword ptr [rsp+48]
    movdqu xmm2, xmmword ptr [rsp+64]
    movdqu xmm3, xmmword ptr [rsp+80]
    add  rsp, 104
    pop  r9
    pop  r8
    pop  rdx
    pop  rcx
    jmp  r11
mv_resolve ENDP

END
'@)
$dir = $PSScriptRoot
$enc = New-Object System.Text.UTF8Encoding($false)
[IO.File]::WriteAllText((Join-Path $dir 'dwmapi_proxy.def'),  (($def -join "`r`n") + "`r`n"), $enc)
[IO.File]::WriteAllText((Join-Path $dir 'dwmapi_stubs.asm'),  (($asm -join "`r`n") + "`r`n"), $enc)
[IO.File]::WriteAllText((Join-Path $dir 'dwmapi_exports.inc'), (($inc -join "`r`n") + "`r`n"), $enc)
Write-Host "generated $($ords.Count) slots, ordinals $base..$($ords[-1])"
